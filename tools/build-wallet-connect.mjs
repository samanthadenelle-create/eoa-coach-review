#!/usr/bin/env node
// =============================================================================
// tools/build-wallet-connect.mjs — WO-1958.
//
// Bundles Assets/WebGLTemplates/Pi/wallet-connect.src.js (+ its core) and the
// @reown AppKit Solana stack into ONE self-contained IIFE,
// `wallet-connect.bundle.js`, written byte-identically into BOTH templates
// (Pi and xNFT) and COMMITTED to git.
//
// ---------------------------------------------------------------------------
// WHY THE OUTPUT IS COMMITTED AND NOT BUILT DURING THE UNITY BUILD
// ---------------------------------------------------------------------------
// The Unity WebGL build must stay hermetic: `tools/web-ship.ps1` fires batchmode
// on a machine that may have no node_modules, and a missing bundler there would
// produce a build that installs, launches, plays, and simply has no Jupiter door
// — the exact SILENT-MISSING-CONTENT failure CLAUDE.md section 16 was written
// about. So the artifact is in the tree, the freshness is asserted by a contract
// row, and the build step is a developer action, not a ship-time dependency.
//
// ---------------------------------------------------------------------------
// FRESHNESS IS A HASH, NOT A TIMESTAMP
// ---------------------------------------------------------------------------
// The emitted file's FIRST LINE is:
//     // EOA_WALLET_CONNECT_BUNDLE srcHash=<sha256-16> coreHash=<sha256-16> esbuild=<ver>
// `tools/web-build-contracts.ps1` re-hashes the two sources and compares. A
// timestamp would go green on a `touch`; a hash cannot. This is the same rule
// tools/build-page-buffer.mjs follows for `buffer`.
//
// ---------------------------------------------------------------------------
// ⛔ THIS SCRIPT HAS NEVER BEEN RUN. Stated plainly (CLAUDE.md section 11B).
// esbuild, @reown/appkit-adapter-solana and @reown/appkit-wallet-button are NOT
// in node_modules on this machine and the lane that wrote this file could not
// install them (it works through a junctioned node_modules). The `define` /
// `inject` choices below are reasoned from the packages' own metadata, not from a
// successful run. The FIRST person to run it should expect to adjust them, and
// should say in the RESULT that they did.
//
// USAGE:  npm run web:bundle
// OUTPUT: the two paths, byte counts, the hashes, and WALLET_CONNECT_BUNDLE_OK.
// =============================================================================

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PI = path.join(root, 'Assets', 'WebGLTemplates', 'Pi');
const XNFT = path.join(root, 'Assets', 'WebGLTemplates', 'xNFT');

const SRC = path.join(PI, 'wallet-connect.src.js');
const CORE = path.join(PI, 'wallet-connect.core.js');
const OUT_NAME = 'wallet-connect.bundle.js';
const CONFIG_NAME = 'reown-config.js';
export const HEADER_MARKER = 'EOA_WALLET_CONNECT_BUNDLE';

export function shortHash(text) {
    return crypto.createHash('sha256').update(text, 'utf8').digest('hex').slice(0, 16);
}

export function headerLine(srcHash, coreHash, esbuildVersion) {
    return `// ${HEADER_MARKER} srcHash=${srcHash} coreHash=${coreHash} esbuild=${esbuildVersion}`;
}

// The generated, GITIGNORED projectId shim. It is a separate one-line file rather
// than a value baked into the bundle so that the committed artifact carries no
// account-specific string and a projectId rotation needs no rebuild.
export function configShim(projectId) {
    return '// GENERATED by tools/build-wallet-connect.mjs - GITIGNORED. Do not commit.\n' +
           'window.EOA_REOWN_PROJECT_ID = ' + JSON.stringify(String(projectId || '')) + ';\n';
}

export function readProjectId(dir) {
    const p = path.join(dir, 'reown.config.json');
    if (!fs.existsSync(p)) return { projectId: '', source: 'absent', path: p };
    try {
        const parsed = JSON.parse(fs.readFileSync(p, 'utf8'));
        return { projectId: String(parsed.projectId || ''), source: 'file', path: p };
    } catch (err) {
        return { projectId: '', source: 'unparseable: ' + err.message, path: p };
    }
}

async function main() {
    let esbuild;
    try {
        esbuild = await import('esbuild');
    } catch (err) {
        // A NAMED refusal, not a stack trace. This is the expected state on a clone
        // that has not run `npm install` since WO-1958 added the devDependency.
        console.error('WALLET_CONNECT_BUNDLE_FAIL esbuild is not installed. ' +
                      'Run `npm install` in the repo root (esbuild is a devDependency ' +
                      'added by WO-1958), then `npm run web:bundle`.');
        process.exit(16);
    }

    const srcText = fs.readFileSync(SRC, 'utf8');
    const coreText = fs.readFileSync(CORE, 'utf8');
    const srcHash = shortHash(srcText);
    const coreHash = shortHash(coreText);

    const result = await esbuild.build({
        entryPoints: [SRC],
        bundle: true,
        format: 'iife',
        platform: 'browser',
        target: ['es2020'],
        minify: true,
        write: false,
        legalComments: 'none',
        define: {
            // AppKit and its transitive deps read both. Unset, the bundle throws
            // ReferenceError on first evaluation and the page never even loads.
            'process.env.NODE_ENV': '"production"',
            'global': 'globalThis'
        },
        // Buffer: the templates already load page-buffer.js (WO-1910) BEFORE this
        // bundle, which installs window.Buffer. So Buffer is deliberately NOT
        // bundled again here — doing so would double a ~50 KB polyfill and, worse,
        // give the page two different Buffer constructors whose instanceof checks
        // disagree.
        external: []
    });

    const bundled = result.outputFiles[0].text;
    const out = headerLine(srcHash, coreHash, esbuild.version) + '\n' + bundled;

    for (const dir of [PI, XNFT]) {
        const target = path.join(dir, OUT_NAME);
        fs.writeFileSync(target, out, 'utf8');
        console.log(`wrote ${target} bytes=${Buffer.byteLength(out, 'utf8')}`);

        const cfg = readProjectId(dir.replace(XNFT, PI));
        if (cfg.projectId) {
            fs.writeFileSync(path.join(dir, CONFIG_NAME), configShim(cfg.projectId), 'utf8');
            console.log(`wrote ${path.join(dir, CONFIG_NAME)} (gitignored, projectId set)`);
        } else {
            console.warn(`WALLET_CONNECT_CONFIG_MISSING ${cfg.path} (${cfg.source}) - ` +
                         'the page will load and the Jupiter door will REFUSE with ' +
                         'reason=no-project-id. Copy reown.config.example.json and ' +
                         'paste the projectId from https://dashboard.reown.com/.');
        }
    }

    console.log(`WALLET_CONNECT_BUNDLE_OK srcHash=${srcHash} coreHash=${coreHash} ` +
                `esbuild=${esbuild.version} bytes=${Buffer.byteLength(out, 'utf8')}`);
}

// Importable for the node test (which checks the header format and the config shim
// WITHOUT running esbuild); executed only when invoked directly.
const invokedDirectly = process.argv[1] &&
    path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (invokedDirectly) {
    main().catch((err) => {
        console.error('WALLET_CONNECT_BUNDLE_FAIL ' + (err && err.message));
        process.exit(16);
    });
}
